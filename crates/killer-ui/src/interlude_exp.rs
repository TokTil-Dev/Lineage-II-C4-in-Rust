pub fn level_bounds(level: i32) -> Option<(i64, i64)> {
    if level <= 0 {
        return None;
    }
    let level = usize::try_from(level).ok()?;
    Some((*EXP_AT_LEVEL.get(level)?, *EXP_AT_LEVEL.get(level + 1)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_the_one_at_0x1023dc58_indexed_by_level() {
        assert_eq!(&EXP_AT_LEVEL[1..5], &[0, 68, 363, 1168]);
        assert_eq!(EXP_AT_LEVEL[80], 4_200_000_000);
        assert_eq!(EXP_AT_LEVEL[100], 99_999_999_999_999);
        assert!(EXP_AT_LEVEL[1..].windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn set_point_exp_takes_the_level_and_the_next_level_entries() {
        assert_eq!(level_bounds(1), Some((0, 68)));
        assert_eq!(level_bounds(79), Some((2_099_275_834, 4_200_000_000)));
        assert_eq!(level_bounds(99), Some((37_193_100_000_000, 99_999_999_999_999)));
        assert_eq!(level_bounds(0), None);
        assert_eq!(level_bounds(100), None);
        assert_eq!(level_bounds(-3), None);
    }
}
